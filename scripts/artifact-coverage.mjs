#!/usr/bin/env node
// scripts/artifact-coverage.mjs
// Generates research/artifact-coverage.md showing which gate artifacts
// each program has produced. The Constitution requires specific files at
// each gate (§7); this script reports the file presence only — the
// human owner attests their content per the gate request.

import fs from "node:fs";
import path from "node:path";

const PROGRAMS = [
  "mpi-nighttime-lights",
  "public-service-data-quality",
  "access-services",
  "digital-performance",
  "air-monitoring",
  "remittance-resilience",
  "grid-reliability-heat",
  "disaster-recovery-lag",
  "migration-displacement-signals",
  "port-hinterland-friction",
  "water-stress-crop-diversification",
  "climate-health-workdays",
  "social-protection-shock-coverage",
  "school-heat-disruption",
  "food-price-climate-transmission",
  "coastal-informal-risk",
  "flood-market-access",
  "invisible-urbanization",
];

const ARTIFACTS = [
  { key: "lit", label: "lit", file: "literature.md" },
  { key: "scoring", label: "scoring", file: "scoring.md" },
  { key: "prereg", label: "prereg", file: "pre-registration.md" },
  { key: "sensitivity", label: "sens", file: "sensitivity.md" },
  { key: "coverage", label: "cov", file: "coverage.md" },
  { key: "results", label: "results", file: "results.md" },
  { key: "internal", label: "rev-int", file: "review-internal.md" },
  { key: "external", label: "rev-ext", file: "review-external.md" },
  { key: "limitations", label: "limits", file: "limitations.md" },
];

// Programs may live at the repo root (newer programs) or under
// luminosity-gap/research/ (older programs imported from the original
// Next.js subproject). Resolve both.
const SEARCH_BASES = [".", "luminosity-gap/research"];

function programDir(slug) {
  for (const base of SEARCH_BASES) {
    const p = path.join(base, slug);
    if (fs.existsSync(p)) return p;
  }
  return null;
}

function check(dir, file) {
  if (!dir) return false;
  return fs.existsSync(path.join(dir, file));
}

function main() {
  const rows = PROGRAMS.map((slug) => {
    const dir = programDir(slug);
    const cells = ARTIFACTS.map((a) => check(dir, a.file) ? "✓" : "·");
    return { slug, dir, cells };
  });

  const md = render(rows);
  fs.writeFileSync("research/artifact-coverage.md", md);
  console.log(`wrote research/artifact-coverage.md — ${PROGRAMS.length} programs × ${ARTIFACTS.length} artifacts.`);
}

function render(rows) {
  const head = ["program", ...ARTIFACTS.map((a) => a.label)];
  const headerRow = `| ${head.join(" | ")} |`;
  const sep = `| ${head.map(() => "---").join(" | ")} |`;
  const body = rows.map((r) => {
    const where = r.dir ? ` _(${r.dir})_` : " _(no folder)_";
    const name = r.dir ? `${r.slug}${where}` : `~~${r.slug}~~${where}`;
    return `| ${[name, ...r.cells].join(" | ")} |`;
  }).join("\n");
  return `# Artifact coverage

Auto-generated by \`scripts/artifact-coverage.mjs\`. Per-program status of
the gate artifacts each tier requires (Constitution §7).

Last refresh: ${new Date().toISOString().slice(0, 10)}

Cell legend:
- ✓ — file exists in the program folder
- · — file does not exist

This script reports presence only. Content quality is attested by the
human owner per the relevant gate request in \`research/gates/\`.

---

${headerRow}
${sep}
${body}

---

## Gate-by-gate requirements (from \`CONSTITUTION.md\` §7)

- **H → PP**: lit (Tier-A/B/C), scoring (≥ 18/30), prereg
- **PP → SR**: results, coverage; pipeline reproducible from clean clone
- **SR → PR**: sens (±50 percent), rev-int, rev-ext (≥ 2 reviewers), limits, Zenodo DOI
`;
}

main();
